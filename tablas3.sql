CREATE TABLE CHOFER (
 NUM_CHOFER INT PRIMARY KEY,
 NOMBRE     VARCHAR(80),
 DIRECCION  VARCHAR(120),
 TELEFONO   VARCHAR(9),
 SUELDO     DECIMAL(8,2),
 FECH_INI   DATE,
 ZONA       VARCHAR(5),
 FOREIGN KEY (ZONA) REFERENCES ZONA(ZONA)
 ON DELETE RESTRICT
);

CREATE TABLE ZONA (
 ZONA      VARCHAR(5) PRIMARY KEY,
 MUNICIPIO VARCHAR(60),
 PROVINCIA VARCHAR(30)
);

CREATE TABLE VEHICULOS (
 COD_VEHIC   INT PRIMARY KEY,
 MATRICULA   VARCHAR(7),
 TONELAJE    DECIMAL(5,2),
 VOLUMEN     DECIMAL(6,2),
 FECH_COMPRA DATE
);

CREATE TABLE USO (
 NUM_CHOFER INT,
 COD_VEHIC  INT,
 PRIMARY KEY (NUM_CHOFER, COD_VEHIC),
 FOREIGN KEY (NUM_CHOFER) REFERENCES CHOFER(NUM_CHOFER)
ON DELETE RESTRICT,
 FOREIGN KEY (COD_VEHIC) REFERENCES VEHICULOS(COD_VEHIC)
ON DELETE RESTRICT
);